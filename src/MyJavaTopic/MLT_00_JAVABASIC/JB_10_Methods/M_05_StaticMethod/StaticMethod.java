package MyJavaTopic.MLT_00_JAVABASIC.JB_10_Methods.M_05_StaticMethod;

public class StaticMethod {
    // Static method
    static void hello() {

        // Print message
        System.out.println("Hello Java");
    }

    public static void main(String[] args) {
// Call static method directly
        hello();
    }
}
