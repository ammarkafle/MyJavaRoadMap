package MyJavaTopic.MLT_00_JAVABASIC.JB_04_DataTypes.DT_00_PrimitiveDataType;

public class PrimitiveDataType {
    public static void main() {

        // There are 8 types of primitive data types in Java.
        int x = 10; // used for normal integers
        float y = 20.59f; // used for long decimal number
        double z = 30.6; // used for small precise decimal number
        boolean a = true; // used for either true or false
        char b = 'A'; // used for single character

        long c = 1989789L; // used for large integers
        short d = 1000; // used for integers
        byte e = 10; // used for small integers

        System.out.println("This is Integer : "+ x);
        System.out.println("This is Float : "+ y);
        System.out.println("This is Double : "+ z);
        System.out.println("THis is Boolean : "+ a);
        System.out.println("This is char : "+ b);

        System.out.println("This is Long : "+ c);
        System.out.println("This is Short: "+ d);
        System.out.println("This is Byte : "+ e);


    }
}
