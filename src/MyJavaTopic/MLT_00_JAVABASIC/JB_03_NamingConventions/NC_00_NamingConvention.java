package MyJavaTopic.MLT_00_JAVABASIC.JB_03_NamingConventions;

public class NC_00_NamingConvention {
    public static void main(String[] args) {

        /* There are various way to declare the
        variables, methods, class, interface, constant,
         package, constructor, boolean, enum. */

        System.out.println("Variable Naming : " + " CamelCase" + "Eg : " + "camelCase");
        System.out.println("Method Naming : " + " CamelCase" + "Eg : " + "camelCase");
        System.out.println("Class Naming : " + " PascalCase" + "Eg : " + "PascalCase");
        System.out.println("Interface Naming : " + " PascalCase" + "Eg : " + "PascalCase");
        System.out.println("Constant Naming : " + " UPPER_SNAKE_CASE" + "Eg : " + "UPPER_SNAKE_CASE");
        System.out.println("Package Naming : " + " lowercase" + "Eg : " + "lowercase");
        System.out.println("Constructor Naming : " + " PascalCase" + "Eg : " + "PascalCase");
        System.out.println("Boolean Variable Naming : " + " is,has,xan,should + PascalCase" + "Eg : " + "isPascalCase");
        System.out.println("Enum Naming : " + " type = PascalCase and values = UPPER_SNAKE_CASE" + "Eg : " + "enum StudentStatus { ACTIVE, INACTIVE,GRADUATED }");

        /*Note
        Variable       → camelCase
        Method         → camelCase
        Class          → PascalCase
        Interface      → PascalCase
        Constant       → UPPER_SNAKE_CASE
        Package        → lowercase
        Constructor    → ClassName
        Boolean        → is/has/can/should
        Enum Types     → PascalCase
        Enum values    → UPPER_SNAKE_CASE
         */


    }
}
