package MyJavaTopic.MLT_00_JAVABASIC.JB_09_ControlStatement.CS_00_ForLoop;

public class FL_00_ForLoop {
    public static void main(String[] args) {
        // Start i from 1
        // Continue the loop while i is less than or equal to 5
        // Increase i by 1 after every iteration
        for (int i = 1; i <= 5; i++) {

            // Print the current value of i
            System.out.println(i);
        }
    }
}
